- 当众干出狠事、出洋相、背信弃义、在拳场/赛道赢下硬仗或上了新闻时，按现场目击者与传播渠道自然写出风声；私下里没人看见、也没人外传的事不会自动传开。`,
  text: `- 外界对玩家的认知完全由具体事迹构成，不再使用声望等级数字。
