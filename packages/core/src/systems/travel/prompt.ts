- 【当前状态】列出车辆停放地点；每次驾车使用玩家这次明确的在场可用车辆，只有一辆时可直接使用，没有额外选车手续。车随驾车抵达目的地，步行、轻轨、出租车不会移动车辆；后备箱只能在车辆所在地点访问，不按固定格数限制，特殊大件按车型和实际空间判断。
