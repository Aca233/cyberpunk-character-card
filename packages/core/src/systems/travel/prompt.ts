import type { RuleModule } from "../../kernel/system";
import type { TravelState } from "./schema";

/** 输入里像要换地方的说法；"进去""溜出去""扔过去"这类趋向补语里的"去"不算 */
const GO =
  /(?<![进出过上下起回跳爬溜钻冲扔推拿抢递送塞])去|前往|打车|出租车|轻轨|NCART|开车|骑车|走过去|赶过去|回家|回公寓|回去|离开|动身|出发/i;
/** 输入里像和车有关的说法 */
const CAR = /车|摩托|追|甩掉|飙|撞|抛弃|扔掉|弃车|取车|叫车|呼叫|泊|停/;

export const travelRules: RuleModule<TravelState> = {
  id: "travel",
  title: "出行、载具和路上偶遇",
  commands: ["vehicle"],
  when: (state, input) =>
    state.encounter !== null ||
    (input.mode !== "ooc" && (GO.test(input.text) || CAR.test(input.text))),
  judge: `- 没有快速移动。玩家在路线面板确认的出行，耗时、路费、到达时间和路上情况都已由系统敲定，不要为路途本身再加无端波折，更不要以「缺少通行证」拦阻玩家进入狗镇；路途遇袭或突发的冲突照物理因果裁决。
- 狗镇准入原则：狗镇黑市与体育场对夜之城佣兵与商客开放进出，常规关口经身份/随身武器扫描或太平洲地下通道即可正常通行；不要凭空要求玩家出示不存在的「通行证」并判 blocked。只有当玩家与幽冥犬（barghest）处于敌对/见面就打状态、公然驾赃车硬闯或拒检动武时，关口才会拦阻升级。
- 自由输入里说要去哪（"打车去来生"、"去狗镇"）按实际路途、交通方式与时间消耗裁决。
- 偷车：没人看着的普通民用车有电子解锁/接线经验常能得手；装了重防盗警报、有人守着或大白天在主街动手极易响警报、引来车主或 NCPD 到场。
- 追车（追人或被追）：车的极速、改装状况、受损程度、对偷来车辆的手生程度与路况车流直接决定能不能甩开或咬住；裁决要写明出岔子时的实在代价（车受损、被逼停或惹出通缉动静）。
- 只有停在身边的可用车辆才能直接开走；车停在别处时，可以先去取车再开车，或远程呼叫自有车驶来（需合理耗时与路况条件），不能无缘无故隔空瞬移。现场同类可用车只有一辆时自动使用，多辆时根据玩家意图明确车辆。
- 不阻拦弃车：玩家随时可以连车带物弃车（无论车里有没有东西、人在不在车旁）；如果车内留有重要证据或危险物品，不阻拦决定，可在结果中点出并让世界继续演变。
- 载具能装多少按车型和真实空间常识判断，不设数字格数。`,
  narrate: `- 【本轮已定的事】里有【出行】时，路途与到达须符合已定的方式、路线和耗时；路上和同伴说话用的是这段路途时间，不另加一次路程。涉及狗镇关口时，若非与幽冥犬敌对或玩家主动挑衅，按例行扫描/接驳放行顺畅写入抵达，不要把已确认的行程写成被卡在关口外进不去。
- 有【路上偶遇】时是本趟路途的素材，这一场合适就让它出现，写成世界自己发生的事，不替玩家决定管不管；玩家不理就让它在屏幕外发展，以后可能找上门；局面不合适可以改写或推迟。没抽到时路上有说得过去的事也可以写，别每趟都写。
- 留意【当前状态】里的「身边的车」和「名下停在别处的车」：如果玩家是开着自己的车来到当前地点，办完事要离开去别处时，顺理成章写清是开车离开（除非玩家主动说坐轻轨、打车或丢下车）；如果车停在别处，玩家说要去取车再开车，或呼叫车辆驶来，要如实交代取车/驶来并开往下一站。
- 若玩家准备弃车或丢下现场而车内还留有重要证据、任务物件或尸体，不要强行拦住，可在正文里自然提醒一句，让玩家自行决定回头拿还是承担后续风险。`,
  text: `- 没有快速移动。玩家在路线面板确认的出行，代码已经推进时间、扣路费、换了地点（写在【本轮已定的事】里）：world 里不要再写 location，time 只能写到达以后。
- 自由输入里说要去哪（"打车去来生"），照常在 world 里写 location（地点 id 或中文名）。代码会核对路程：500 米内算走过去，用时代码按步行补；更远的自动转成一次出行，代码按路线表推进时间、扣路费，方式按在场有车开车、两头有站坐轻轨、钱够打车、都不行走路来挑。正文里写的走法、用时尽量和这个对上，time 不要写得比到达还早。
- 【极重要 · 单轮取车再开车/短途开车同步】：如果正文里在同一轮先去别处取回车、再开着它前往最终目的地，或者呼叫车辆驶来后开走，或开着车走了短途/去了新地点（autoMove 不会自动带车时），必须按先后拆成两段 world(location) **或**在最终到达的 world 之后紧跟一条 vehicle(action: "drive", vehicle: "车id", location: "最终地点id或留空取当前地点", reason: "取车并开到目的地")，保证车辆位置与正文完全一致，绝不把已经开走的车继续留在旧地点。
- 【当前状态】或【本轮已定的事】里的路上偶遇是代码抽的素材，合适就写出来；玩家可以不理，不理就让事情在屏幕外发展。
- 载具写 vehicle：buy 买车（model 写车型 id，代码按车价扣钱）；steal 偷车（在物理上真把防盗摆平并开走，写 witnesses）；drive 同步名下车辆被取回/开走/呼叫到的新停放点（location 缺省为当前地点，自动同步车内物品）；damage 受损一档（受损再坏就报废）、wreck 直接报废；repair 修车（代码按车价一成收钱，要人在车旁）；abandon 弃车（随时允许，车内留置物品会一并留在弃车地点，不要求先取空）；chase 追逐（stake 写承受或导致的代价：damage、stopped、heat）。远处发生的车辆损坏要写 location。`,
};
