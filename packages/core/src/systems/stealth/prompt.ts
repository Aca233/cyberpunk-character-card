import type { RuleModule } from "../../kernel/system";
import type { StealthState } from "./schema";

/** 输入里像要潜入的说法 */
const SNEAK =
  /潜入|潜行|摸进|溜进|溜过|偷偷|悄悄|躲开(守卫|摄像头|巡逻)|绕过(守卫|摄像头|巡逻)|不被发现|别被发现|翻墙|从后门/;

export const stealthRules: RuleModule<StealthState> = {
  id: "stealth",
  title: "潜入和警戒",
  commands: ["alert"],
  when: (state, input) => state.level > 0 || (input.mode !== "ooc" && SNEAK.test(input.text)),
  judge: `- 潜入时代码按场景记警戒度 0–3：没察觉、起疑、搜索、交战。
- 潜入露出破绽、惊动守卫或触发传感器的默认后果是警戒升一档，不直接扣血；真要吃流弹或触发致命陷阱必须先有明确物理因果。
- 起疑（1）时守卫加强巡逻、视线收紧，想继续硬混过去会困难得多；搜索（2）时主要通道已被堵住，隐蔽接近几近不可能。
- 好办法（提前扫清路线、穿对伪装、骇掉摄像头、借天气或噪音掩护）直接打通物理条件，能顺理成章潜入成功。
- 降警戒每个场景最多一档，交战档不能再降，只能打或撤。`,
  narrate: `- 警戒度：起疑（1）守卫加强巡逻；搜索（2）出口和要道有人把守，部分路线关闭，增援在路上；交战（3）守卫已经发现你，按现场位置、掩体和退路写交战局面，不预定谁先命中；打斗过程交给叙事，系统只记录实际发生的后果。
- 降警戒：躲起来等一阵、处理掉起疑的人、骇掉警报；正文写出是怎么降下来的。
- 没被发现就完成目标时写得干净利落；这个场景闹到过搜索档，收尾时消息会传开。`,
  text: `- 潜入时代码按场景记警戒度 0–3：没察觉、起疑、搜索、交战。被察觉时写 alert（delta 为正），降警戒写降档（delta 取负）。
- 潜入露出破绽、惊动守卫或触发传感器的默认后果是警戒升级（发 alert 升档），不扣血；真要吃流弹或触发致命陷阱必须先有明确物理因果。
- 起疑（1）：守卫加强巡逻、视线收紧，继续靠近极易露馅。搜索（2）：出口和要道有人把守，部分路线关闭，增援在路上。交战（3）：尚未登记交战时发 combat start；按现场位置、掩体和退路叙述交战，不预定谁先命中。实际发生伤亡后才记录 combat wound 或 foe，收场时写 combat end。
- 降警戒：躲起来等一阵（推进时间）、处理掉起疑的人、骇掉警报；每个场景最多降一档，交战档不能再降，只能打或撤。
- 好办法（扫描路线、穿对伪装、骇掉摄像头、天气掩护）直接打通物理条件，能顺理成章潜入过去。
- 没被发现就完成目标，委托按 clean 结算；这个场景警戒到过搜索档，收尾时代码按风声给热度升级，不另写 event。`,
};
