import type { RuleModule } from "../../kernel/system";
import type { StealthState } from "./schema";

/** 输入里像要潜入的说法 */
const SNEAK =
  /潜入|潜行|摸进|溜进|溜过|偷偷|悄悄|消音|无声|暗杀|摸哨|躲开(守卫|摄像头|巡逻)|绕过(守卫|摄像头|巡逻)|不被发现|别被发现|翻墙|从后门/;

export const stealthRules: RuleModule<StealthState> = {
  id: "stealth",
  title: "潜入和警戒",
  commands: ["alert"],
  when: (state, input) =>
    Object.values(state.sites).some((site) => site.level > 0) ||
    (input.mode !== "ooc" && SNEAK.test(input.text)),
  judge: `- 警戒按地点持续保存：没察觉、起疑、搜索、交战描述已确认的现场态势，不按场次发放降警戒次数。
- 守卫是否听见、看见、识别以及能否通知他人，分别按现场视线、设备、距离、证据和实际通信判断；警戒标签不自动封路、召来增援或决定命中。
- 武器声学直接影响听觉暴露：以【物理与安防现状】和【当前状态】的武器消音状态为准。未消音枪械开火会产生清晰枪声惊动附近守卫与目击者（除非现场有剧烈环境轰鸣掩盖）；已消音枪械和冷兵器不会触发远距枪声警报，但近距机械声、倒地动静、视线或监控仍可暴露。
- 已发生的停火、排除误报、撤销搜索可以降低警戒；切场或离开本身不会清除现场事实，也不会自动报警。`,
  narrate: `- 沿用当前位置实际警戒与感知事实。搜索不代表所有出口封死或警方知情，增援须有实际呼叫及可达路线。
- 消音与未消音武器开火须严格按当前声学状态写现场动静：已消音武器暗杀只写近距压低的声响与目击边界，不无故引来整片区域枪声警报；未消音枪械开火须真实反映枪声传播与惊动。
- 警戒升降写出实际原因。冲突停止可以转入搜索或解除戒备；离开后原处警戒仍然存在，目的地使用自己的现场状态。
- 没被发现就完成目标，不追加暴露；消息传播必须有目击、录像或实际通信。`,
  text: `- alert 只记录实际发生的地点警戒变化：delta 正值升级、负值降低，reason 说明对应感知、停火、误报排除或搜索解除。
- location 写变化发生的已知地点；不写默认本轮行动开始地点。同轮已经移动时，原处搜索不能记到目的地。
- 警戒不随切场归零，无每场降低次数限制。交战结束可以降低警戒，但不能用降档抹除实际伤亡、录像或已发出的警报。
- 只有实际交火才记录 combat；警方热度沿用真实目击、报警、录像与传播事件，切场本身不发 event 或 heat。`,
};
