export function examplesSection(): string {
  const blocks = PROMPT_EXAMPLES.map((e, i) =>
    [
      `${i + 1}. ${e.topic}`,
      `玩家：${e.input}`,
      `✗ ${e.bad}`,
      `✓ ${e.good}`,
      `要点：${e.why}`,
    ].join("\n"),
  );
  return `【好坏示例】\n只示范写法，不是剧情；人物和地点按当前存档来。\n\n${blocks.join("\n\n")}`;
}

/** 内容包的转折和两难素材；没有时不放进提示词 */
export function twistSection(data: Readonly<Record<string, unknown>>): string | undefined {
  if (data.twists === undefined) return undefined;
  const twists = TwistCatalogSchema.parse(data.twists);
  if (twists.length === 0) return undefined;
  const lines = twists.map(
    (t) => `- ${t.id}（${t.kind === "twist" ? "转折" : "两难"}）：${t.text}`,
  );
  return `【转折和两难素材】\n挂委托写 twist、或者剧情需要一个没有标准答案的选择时，可以取用、改写或组合；不强制套用，同一条别在一个存档里反复用。\n${lines.join("\n")}`;
}
